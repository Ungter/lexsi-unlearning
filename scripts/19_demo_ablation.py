"""Demo (PLAN 8.4, "one live attack"): the same calculus test problem answered by an unlearned model before and after the
training-free attack of scripts/17_local_abl.py (one direction per edited layer projected out of the w2 output; the
directions come from 128 dev prompts on the attacked model itself, no gradient steps, no reference model).

  python scripts/19_demo_ablation.py --model models/surgery/l2_calc_b25 --layers 6,7,8 --n 3 --out docs/DEMO_ABLATION.md
"""
from __future__ import annotations

import argparse
import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from lfm3u.audit.mathgrade import grade_item  # noqa: E402
from lfm3u.data.splits import read_jsonl  # noqa: E402

spec = importlib.util.spec_from_file_location("la", ROOT / "scripts" / "17_local_abl.py")
LA = importlib.util.module_from_spec(spec)
spec.loader.exec_module(LA)
H = LA.H


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", required=True)
    ap.add_argument("--layers", required=True)
    ap.add_argument("--site", default="w2")
    ap.add_argument("--n", type=int, default=3)
    ap.add_argument("--max-new", type=int, default=1536)
    ap.add_argument("--show-chars", type=int, default=700)
    ap.add_argument("--show", type=int, default=3, help="problems to print; ones the attack flips to correct come first")
    ap.add_argument("--out", default="docs/DEMO_ABLATION.md")
    a = ap.parse_args()

    import torch
    from transformers import AutoModelForCausalLM, AutoTokenizer

    tok = AutoTokenizer.from_pretrained(a.model, trust_remote_code=True)
    model = AutoModelForCausalLM.from_pretrained(a.model, trust_remote_code=True, dtype=torch.bfloat16).to(H.device()).eval()
    data = ROOT / "data"
    fr = [r for lvl in (1, 2, 3) for r in read_jsonl(data / f"calculus/level{lvl}/dev.jsonl")]
    cr = [r for t in ("arithmetic", "algebra", "precalculus") for lvl in (1, 2, 3) for r in read_jsonl(data / f"{t}/level{lvl}/dev.jsonl")]
    H.seeded("abl", "f").shuffle(fr)
    H.seeded("abl", "c").shuffle(cr)
    layers = [int(x) for x in a.layers.split(",")]
    keys = [(a.site, l) for l in layers]
    mf = LA.site_means(model, tok, [H.chat_ids(tok, r["instruction"]) for r in fr[:128]], keys)
    mc = LA.site_means(model, tok, [H.chat_ids(tok, r["instruction"]) for r in cr[:128]], keys)
    specs = [(s, l, ((mf[(s, l)] - mc[(s, l)]) / (mf[(s, l)] - mc[(s, l)]).norm()).cpu(), 0.0, "proj") for s, l in keys]
    rows = read_jsonl(ROOT / "attack_data/_inputs/math_calc_test.jsonl", allow_test=True)
    H.seeded("abl", "test").shuffle(rows)
    rows = rows[:a.n]
    prompts = [H.chat_ids(tok, r["instruction"]) for r in rows]
    before = H.hf_generate(model, tok, prompts, a.max_new, bs=len(prompts))
    hooks = LA.ablate(model, specs)
    try:
        after = H.hf_generate(model, tok, prompts, a.max_new, bs=len(prompts))
    finally:
        for h in hooks:
            h.remove()
    clip = lambda t: (t[:a.show_chars] + (" [...]" if len(t) > a.show_chars else "")).replace("\n", "\n> ")  # noqa: E731
    md = ["# Demo: training-free recovery of an unlearned skill", "",
          f"Model `{Path(a.model).as_posix()}`. Attack: project one direction out of the `{a.site}` output at layers {a.layers} "
          "(forget-minus-contrast mean over 128 calculus vs 128 other-math DEV prompts, computed on the unlearned model itself; "
          f"no gradient steps, no access to the original model). Greedy decoding, {a.max_new}-token cap. Generated by "
          "`scripts/19_demo_ablation.py`; the full test-set numbers are in `docs/AUDIT.md` §5b.", ""]
    graded = [(r, b, c, grade_item(r, b["text"]), grade_item(r, c["text"])) for r, b, c in zip(rows, before, after)]
    nb, nc = sum(x[3]["correct"] for x in graded), sum(x[4]["correct"] for x in graded)
    md += [f"On these {len(rows)} test problems: {nb} correct before, {nc} after. Shown: {a.show}, problems the attack flips first.", ""]
    graded.sort(key=lambda x: not (x[4]["correct"] and not x[3]["correct"]))
    for r, b, c, gb, gc in graded[:a.show]:
        md += [f"## {r['instruction']}", "", f"Gold: `{r['answer']}`", "",
               f"**Unlearned model** ({b['n_tokens']} tokens{', hit the cap' if b['truncated'] else ''}; graded "
               f"{'correct' if gb['correct'] else 'wrong'}):", "", "> " + clip(b["text"]), "",
               f"**Same weights, direction ablated** ({c['n_tokens']} tokens{', hit the cap' if c['truncated'] else ''}; graded "
               f"{'correct' if gc['correct'] else 'wrong'}):", "", "> " + clip(c["text"]), ""]
    Path(a.out).write_text("\n".join(md) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
